export function getAccount(accountId: string): Account | undefined {
  return accounts.find((a) => a.accountId === accountId);
}

export function getOrder(orderId: string): Order | undefined {
  return orders.find((o) => o.orderId.toUpperCase() === orderId.toUpperCase());
}

export function getTicket(ticketId: string): Ticket | undefined {
  return tickets.find((t) => t.ticketId.toUpperCase() === ticketId.toUpperCase());
}
